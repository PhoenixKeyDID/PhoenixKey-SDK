"""Verify-only client for 3rd-party backends.

Resolves a user's public key from PhoenixKey, then verifies ECDSA P-256 signatures
locally. The rules (key status gate, owner-role gate, ``key_mismatch``, ±60 s
skew, canonical JSON, envelope bytes) are the ones the TypeScript SDK applies;
``reason`` strings are identical. The cross-language vectors in
``tests/vectors/vectors.json`` are generated by running the TypeScript code.
"""

from __future__ import annotations

import json
import math
import time
from dataclasses import dataclass
from typing import Any, Callable, Mapping
from urllib.parse import quote

from ._crypto import HexLengthError, hex_to_bytes, p256_verify_sha256
from ._http import Fetch, HttpResponse, make_urllib_fetch
from .canonical import canonical_json_bytes
from .envelope import encode_legacy_concat, encode_rp_auth_v1
from .errors import PhoenixKeyError


DEFAULT_PHOENIXKEY_API_URL = "https://api.phoenixkey.me/api/v1"
TIMESTAMP_SKEW_SEC = 60
DEFAULT_CACHE_TTL_MS = 0

# JavaScript's String.prototype.trim() whitespace set (WhiteSpace + LineTerminator).
_JS_WHITESPACE = "".join(
    chr(c)
    for c in (
        0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0xA0, 0x1680,
        *range(0x2000, 0x200B),
        0x2028, 0x2029, 0x202F, 0x205F, 0x3000, 0xFEFF,
    )
)
# Characters encodeURIComponent leaves alone, beyond letters and digits.
_URI_COMPONENT_SAFE = "-_.!~*'()"


@dataclass(frozen=True)
class IdentityPubkey:
    """A pubkey record as returned by ``GET /identity/{did}/pubkey``."""

    public_key_hex: str
    key_role: str | None = None
    key_id: str | None = None
    status: str | None = None
    created_at: str | None = None
    revoked_at: str | None = None


@dataclass(frozen=True)
class VerifyResult:
    valid: bool
    user_did: str
    #: Why verification failed (only when ``valid`` is False).
    reason: str | None = None
    #: Auth-proof flow only: which message form matched. ``"legacy"`` means the
    #: caller has not moved to ``PHOENIXKEY_RP_AUTH:v1`` yet.
    envelope: str | None = None


def normalize_hex(hex_str: str | None) -> str | None:
    """Drop a ``0x`` prefix, trim, lowercase. Empty or absent -> ``None``."""
    if hex_str is None:
        return None
    s = hex_str[2:] if hex_str[:2] in ("0x", "0X") else hex_str
    s = s.strip(_JS_WHITESPACE).lower()
    return s or None


def _cache_key(user_did: str, wanted_hex: str | None) -> str:
    return f"{user_did}\u0000{wanted_hex if wanted_hex is not None else 'latest'}"


def _is_key_usable(key: IdentityPubkey) -> bool:
    # Fail closed: only an explicit "active" passes; unknown values do not.
    return key.status == "active"


_MAX_SAFE_INTEGER = 2**53 - 1


def _within_skew(ts: object, now: int, *, envelope_integer: bool = False) -> bool:
    """The ±60 s gate shared by ``verify_auth_proof`` and ``verify_intent``.

    Fails closed: anything that is not a real, finite number is outside the
    window. ``abs(now - nan) > 60`` is ``False`` in Python (and in JavaScript), so
    without the type and ``isfinite`` checks a NaN -- which ``json.loads`` accepts
    as the bare token ``NaN`` -- would pass the gate. ``envelope_integer`` also
    requires a value the ``RP_AUTH`` envelope can encode (a non-negative integer,
    a whole-number float allowed), so the auth-proof flow never raises
    ``ValueError`` from the envelope encoder for a bad timestamp.
    """
    if isinstance(ts, bool) or not isinstance(ts, (int, float)):
        return False
    if isinstance(ts, float) and not math.isfinite(ts):
        return False
    if envelope_integer:
        if isinstance(ts, float) and not ts.is_integer():
            return False
        if not 0 <= ts <= _MAX_SAFE_INTEGER:
            return False
    # Same comparison direction as the TypeScript gate (reject when `> 60`). That is
    # exactly why the `isfinite` check above is load-bearing: NaN makes this False.
    if abs(now - ts) > TIMESTAMP_SKEW_SEC:
        return False
    return True


def _reject_json_constant(name: str) -> Any:
    raise ValueError(f"non-standard JSON constant: {name}")


def _strict_json(text: str) -> Any:
    """Parse JSON the way ``JSON.parse`` in the TypeScript SDK does.

    ``json.loads`` accepts bare NaN / Infinity / -Infinity; ``JSON.parse``
    rejects them. Without this, a signed token whose exp is NaN passes the
    expiry gate (every comparison with NaN is False). ``json.loads`` also raises
    ``RecursionError`` on deeply nested input -- a few KB is enough on some
    interpreters -- and that input arrives before any signature check, so it is
    reported as a ``ValueError`` like any other malformed body.
    """
    try:
        return json.loads(text, parse_constant=_reject_json_constant)
    except RecursionError:
        raise ValueError("JSON nesting too deep") from None


def _utf8_json(body: bytes) -> Any:
    return _strict_json(body.decode("utf-8"))


class PhoenixKeyVerifier:
    """Verify signatures made with a user's PhoenixKey device key.

    Parameters mirror the TypeScript ``VerifierConfig``:

    ``phoenixkey_api_url``
        API base including ``/api/v1``. Default ``https://api.phoenixkey.me/api/v1``.
    ``cache_ttl_ms``
        Key cache TTL. **Default 0 (no cache)**: a cached entry keeps verifying a
        key the owner has since revoked, for the length of the TTL.
    ``accept_legacy_envelope``
        Also accept the legacy ``challenge:domain:timestamp`` form in
        :meth:`verify_auth_proof`. Default True during migration.

    Python-only knobs: ``fetch`` (inject an HTTP function
    ``(url, headers) -> HttpResponse``), ``timeout`` (seconds, default transport),
    ``clock`` (``() -> seconds since epoch``, for tests).
    """

    def __init__(
        self,
        phoenixkey_api_url: str | None = None,
        *,
        cache_ttl_ms: int = DEFAULT_CACHE_TTL_MS,
        accept_legacy_envelope: bool = True,
        fetch: Fetch | None = None,
        timeout: float = 10.0,
        clock: Callable[[], float] = time.time,
    ) -> None:
        url = phoenixkey_api_url if phoenixkey_api_url is not None else DEFAULT_PHOENIXKEY_API_URL
        self._api_url = url.rstrip("/")
        self._cache_ttl_ms = cache_ttl_ms
        self._accept_legacy = accept_legacy_envelope
        self._fetch: Fetch = fetch if fetch is not None else make_urllib_fetch(timeout)
        self._clock = clock
        self._cache: dict[str, tuple[IdentityPubkey, float]] = {}

    # ── public API ────────────────────────────────────────────────────────────

    def verify_auth_proof(
        self, *, user_did: str, signature: str, challenge: str, domain: str, timestamp: int
    ) -> VerifyResult:
        """Verify the proof returned by a PhoenixKey login flow.

        Rebuilds the ``PHOENIXKEY_RP_AUTH:v1`` envelope and checks the signature
        against the **newest owner key** of ``user_did`` (no ``public_key_hex``
        is accepted here -- same as the TypeScript SDK). Enforces ±60 s skew. A
        ``timestamp`` that is not a finite non-negative whole number (``NaN``, a
        string, ``100.5``) is ``timestamp_skew``, never an exception.
        """
        now = int(self._clock())
        if not _within_skew(timestamp, now, envelope_integer=True):
            return VerifyResult(False, user_did, "timestamp_skew")

        # Resolve once, then try each envelope on that same key.
        resolved = self._resolve_for_verify(user_did)
        if isinstance(resolved, VerifyResult):
            return resolved

        v1 = self._verify_with_key(
            resolved,
            user_did,
            encode_rp_auth_v1(user_did=user_did, domain=domain, challenge=challenge, timestamp=timestamp),
            signature,
        )
        if v1.valid:
            return VerifyResult(True, user_did, None, "v1")
        if not self._accept_legacy:
            return v1
        legacy = self._verify_with_key(
            resolved,
            user_did,
            encode_legacy_concat(domain=domain, challenge=challenge, timestamp=timestamp),
            signature,
        )
        # When both fail, report v1's reason: v1 is the correct form.
        return VerifyResult(True, user_did, None, "legacy") if legacy.valid else v1

    def verify_intent(
        self,
        *,
        user_did: str,
        intent: Mapping[str, Any],
        signature: str,
        public_key_hex: str | None = None,
    ) -> VerifyResult:
        """Verify a signed intent (sign-request flow).

        ``intent`` is the dict that was signed (``type``, ``body``, ``domain``,
        ``nonce``, ``timestamp``, ``display_text``, ...). Pass ``public_key_hex``
        (the ``public_key_hex`` of the SSE ``signed`` event) when the DID has
        several devices; it is only a hint for the lookup -- the signature is
        always checked against the key the server returns for that exact
        (DID, key). The caller must still check ``nonce`` uniqueness.
        """
        ts = intent.get("timestamp") if isinstance(intent, Mapping) else None
        # TypeScript lets a missing timestamp (and NaN) through the skew gate
        # (the comparison is false). A verifier must not: fail closed.
        now = int(self._clock())
        if not _within_skew(ts, now):
            return VerifyResult(False, user_did, "timestamp_skew")
        resolved = self._resolve_for_verify(user_did, public_key_hex)
        if isinstance(resolved, VerifyResult):
            return resolved
        return self._verify_with_key(resolved, user_did, canonical_json_bytes(intent), signature)

    def resolve_key(self, user_did: str, public_key_hex: str | None = None) -> IdentityPubkey:
        """Fetch the full key record (cached if ``cache_ttl_ms`` > 0).

        Does NOT filter by status: a revoked key is returned as the server
        reports it. Without ``public_key_hex`` it is the newest owner key; with
        it, that exact key (any role). A 404 is raised, never replaced by the
        newest key.
        """
        wanted = normalize_hex(public_key_hex)
        ck = _cache_key(user_did, wanted)
        cached = self._cache.get(ck)
        if cached is not None and cached[1] > self._clock() * 1000:
            return cached[0]
        key = self._resolve_via_phoenixkey(user_did, wanted)
        if self._cache_ttl_ms > 0:
            self._cache[ck] = (key, self._clock() * 1000 + self._cache_ttl_ms)
        return key

    def resolve_pubkey(self, user_did: str, public_key_hex: str | None = None) -> str:
        """Public key hex of the current owner key. Raises if revoked.

        With ``public_key_hex`` it also raises ``key_role_not_owner`` unless that
        key is an owner key.
        """
        key = self.resolve_key(user_did, public_key_hex)
        if not _is_key_usable(key):
            raise PhoenixKeyError(
                status=200,
                code="key_revoked",
                message=(
                    f"Owner key was revoked at {key.revoked_at}"
                    if key.revoked_at
                    else f"Owner key is not active (status={key.status})"
                ),
            )
        if normalize_hex(public_key_hex) is not None and key.key_role != "owner":
            raise PhoenixKeyError(
                status=200,
                code="key_role_not_owner",
                message=f'Key role is "{key.key_role}", not "owner"',
            )
        return key.public_key_hex

    # ── internals ─────────────────────────────────────────────────────────────

    def _resolve_for_verify(
        self, user_did: str, public_key_hex: str | None = None
    ) -> IdentityPubkey | VerifyResult:
        wanted = normalize_hex(public_key_hex)
        try:
            key = self.resolve_key(user_did, wanted)
        except Exception as e:  # noqa: BLE001 - any lookup failure is a "no", not a crash
            return VerifyResult(False, user_did, f"resolve_failed: {e}")
        if not _is_key_usable(key):
            reason = f"key_revoked: {key.revoked_at}" if key.revoked_at else "key_revoked"
            return VerifyResult(False, user_did, reason)
        if wanted is not None:
            # Lookup by exact key returns records of every role; the "newest"
            # path only ever returns an owner. Keep the invariant: only owner
            # keys sign intents / logins.
            if key.key_role != "owner":
                return VerifyResult(False, user_did, "key_role_not_owner")
            # The signature is only ever checked on the key the caller named.
            if normalize_hex(key.public_key_hex) != wanted:
                return VerifyResult(False, user_did, "key_mismatch")
        return key

    @staticmethod
    def _verify_with_key(
        key: IdentityPubkey, user_did: str, message: bytes, signature_hex: str
    ) -> VerifyResult:
        if not isinstance(signature_hex, str):
            return VerifyResult(False, user_did, "verify_failed: signature must be a hex string")
        try:
            sig = hex_to_bytes(signature_hex)
            pub = hex_to_bytes(key.public_key_hex)
        except HexLengthError as e:
            return VerifyResult(False, user_did, f"verify_failed: {e}")
        except ValueError:
            return VerifyResult(False, user_did, "signature_invalid")
        valid = p256_verify_sha256(sig, message, pub)
        return VerifyResult(valid, user_did, None if valid else "signature_invalid")

    def _resolve_via_phoenixkey(self, user_did: str, wanted_hex: str | None) -> IdentityPubkey:
        query = f"?key={quote(wanted_hex, safe=_URI_COMPONENT_SAFE)}" if wanted_hex else ""
        url = f"{self._api_url}/identity/{quote(user_did, safe=_URI_COMPONENT_SAFE)}/pubkey{query}"
        res: HttpResponse = self._fetch(url, {"Accept": "application/json"})
        if not res.ok:
            raise PhoenixKeyError(
                status=res.status,
                code="resolve_failed",
                message=f"PhoenixKey pubkey lookup failed: {res.status}",
            )
        try:
            body = _utf8_json(res.body)
        except (ValueError, UnicodeDecodeError) as e:
            raise PhoenixKeyError(
                status=res.status, code="resolve_failed", message=f"Invalid JSON in pubkey response: {e}"
            ) from e
        rec = body.get("result") if isinstance(body, dict) else None
        pub = rec.get("public_key_hex") if isinstance(rec, dict) else None
        if not isinstance(pub, str) or not pub:
            raise PhoenixKeyError(status=res.status, code="resolve_failed", message="Empty pubkey in response")

        def opt(name: str) -> str | None:
            v = rec.get(name)
            return v if isinstance(v, str) else None

        return IdentityPubkey(
            public_key_hex=pub,
            key_role=opt("key_role"),
            key_id=opt("key_id"),
            status=opt("status"),
            created_at=opt("created_at"),
            revoked_at=opt("revoked_at"),
        )
